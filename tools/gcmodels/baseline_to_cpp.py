# baseline.json (survey.py) -> runtime/src/gcmodel/gcm_baseline.inc for the app's converter
import json
import os

here = os.path.dirname(os.path.abspath(__file__))
b = json.load(open(os.path.join(here, 'baseline.json')))
out = ['// generated by tools/gcmodels/baseline_to_cpp.py from baseline.json (survey.py over %d custom model packs):' % b['packs'],
       '// how far the game\'s original parts are from HD\'s (shape: % of GameCube vertices near an HD one; texture:',
       '// mean difference to HD\'s texture scaled down). Numbers only.',
       'static const std::pair<const char*, double> kBaseGeometry[] = {']
out += ['    {"%s", %.1f},' % (k, v) for k, v in sorted(b['geometry'].items())]
out += ['};', 'static const std::pair<const char*, double> kBaseTexture[] = {']
out += ['    {"%s", %.1f},' % (k, v) for k, v in sorted(b['texture'].items())]
out += ['};', '']
open(os.path.join(here, '../../runtime/src/gcmodel/gcm_baseline.inc'), 'w').write('\n'.join(out))
print(len(b['geometry']), len(b['texture']))
