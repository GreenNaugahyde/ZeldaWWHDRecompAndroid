# The game's townspeople and others on the common rig (backbone, neck, head, shoulder, arm, leg bones), as loot outfits
# (notes/loot.md). Writes runtime/src/gcmodel/hd_outfit_people.inc (ArmorDef rows).
#   python3 outfit_survey.py GAME_DIR OUT.inc
import hashlib
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import nintendo as nin  # noqa: E402
from convert import Bfres  # noqa: E402


NOT_BODIES = {'Btd', 'Dr', 'Dr2', 'Gm', 'Mozo', 'Hr', 'Vmr', 'So', 'Bms', 'Doguu', 'bigelf', 'Bb', 'Oq', 'Kp', 'Ki'}  # giants, birds, plants, statues


def archives(game):
    obj = os.path.join(game, 'content/Common/Object')
    for n in sorted(os.listdir(obj)):
        if n.endswith('.szs'):
            yield n, open(os.path.join(obj, n), 'rb').read()
    pk = os.path.join(game, 'content/Common/Pack')
    for p in sorted(os.listdir(pk)):
        if p.endswith('.pack') and 'permanent' in p:
            files = nin.sarc(open(os.path.join(pk, p), 'rb').read())
            for n in sorted(files):
                if n.endswith('.szs') and not os.path.exists(os.path.join(obj, n)):
                    yield n, files[n]


def main():
    game, out = sys.argv[1:3]
    rows, seen, seen_mesh = [], set(), set()
    # (rated Bad by the user)
    bad = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'outfit_bad.txt')
    rejected = set(open(bad).read().split()) if os.path.exists(bad) else set()
    for an, data in archives(game):
        if an.startswith(('sea_', 'System', 'Always', 'Dalways', 'Link', 'LkAnm', 'LkD', 'Figure', 'Auc', 'Bmsw', 'Bmcon1', 'Bm2', 'Rsh', 'Sarace')):
            continue
        try:
            files = nin.sarc(nin.yaz0(data) if data[:4] == b'Yaz0' else data)
        except Exception:
            continue
        for bn, b in files.items():
            if not bn.endswith('.bfres') or b[:4] != b'FRES':
                continue
            try:
                f = Bfres(b)
                models = f.group(f.section(0))
            except Exception:
                continue
            heads = sorted(n for n, _ in models if 'head' in n and not n.endswith('_bmt'))
            arms = sorted(n for n, _ in models if 'arm' in n and 'head' not in n)
            bodies = 0  # (the n-th body of a file wears its n-th head when the names do not tell)
            for mn, fm in models:
                try:
                    names = {n for n, _ in f.group(f.rel(f.rel(fm + 12) + 0x10))}
                    nv = sum(f.u32(f.rel(fm + 16) + f.u16(so + 0x12) * 0x20 + 8) for _, so in f.group(f.rel(fm + 20)))
                except Exception:
                    continue
                lows = ' '.join(names).lower()
                common = bool({'backbone', 'backbone1', 'backbone0'} & names) and 'head' in names and 'legL1' in names and 'waist' in names and bool({'armL1', 'armL'} & names)
                other = any(w in lows for w in ('mune', 'chest', 'hara', 'stomach')) and any(w in lows for w in ('kubi', 'neck', 'atama', 'head', 'kao')) and any(w in lows for w in ('ude', 'arm_', 'shoulder')) and an[:-4] not in NOT_BODIES
                if not (common or other) or nv < 200 or nv > 5000 or 'invisible' in mn or 'antiindirect' in mn:
                    continue
                if (mn.replace('_bmt', '').replace('_comp', '').replace('_nomal', ''), nv) in seen_mesh:
                    continue
                seen_mesh.add((mn.replace('_bmt', '').replace('_comp', '').replace('_nomal', ''), nv))
                if (an, bn, mn) in seen:
                    continue
                seen.add((an, bn, mn))
                sid = 'f' + hashlib.md5(('outfit/%s/%s/%s' % (an, bn, mn)).encode()).hexdigest()[:10]
                if sid in rejected:
                    continue
                # (many have their head as a model of its own: sa -> sa01_head, sa02_bmt -> sa02_head, p1b_body_bmt -> p1b_head)
                base = mn.replace('_bmt', '').replace('_body', '')
                head = next((h for h in heads if h.startswith((base + '01', base + 'a_'))), None) or next((h for h in heads if h.startswith(base)), None)
                if head is None and heads:
                    head = heads[min(bodies, len(heads) - 1)]
                arm = arms[min(bodies, len(arms) - 1)] if arms and 'armL' in names and 'armL1' not in names else ''
                bodies += 1
                if arm:
                    head = (head or '') + '|' + arm  # (arms that are a model of their own: the Rito's)
                rows.append((sid, '%s %s' % (an[:-4], base), an, bn, mn, head or ''))
    with open(out, 'w') as o:
        o.write('// Generated by tools/gcmodels/outfit_survey.py: the game\'s people on the common rig, as loot outfits. Do not edit.\n')
        for sid, name, an, bn, mn, head in rows:
            o.write('{"%s", "%s", "%s", "%s", "%s", {-2}, "%s", 0, 1, {0, 0, 0}, false, 10, false, 0},\n' % (sid, name, an, bn, mn, head))
    print(len(rows), 'people')


if __name__ == '__main__':
    main()
