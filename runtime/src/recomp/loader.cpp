// imported functions without an HLE implementation: one stub each, so the log can name them
constexpr size_t kStubs = 1024;
const char* g_stub_lib[kStubs];
const char* g_stub_name[kStubs];
template <size_t I>
void unimplemented_stub(Cpu* c) { hle_unimplemented(c, g_stub_lib[I], g_stub_name[I]); }
template <size_t... I>
constexpr std::array<PpcFunc, kStubs> make_stubs(std::index_sequence<I...>) { return {&unimplemented_stub<I>...}; }
constexpr std::array<PpcFunc, kStubs> g_stubs = make_stubs(std::make_index_sequence<kStubs>());

// what the game code links against: libwwhd's exported symbols (runtime, HLE, hooks), and for
// imports without HLE an unimplemented stub
struct Resolver {
    void* self = nullptr;
    std::unordered_map<std::string, std::pair<std::string, std::string>> imports;  // imp_* -> (lib, name)
    std::unordered_map<std::string, void*> stubbed;
    size_t stubs = 0;
    std::mutex m;

    void* resolve(const std::string& sym) {
        if (void* p = dlsym(self, sym.c_str())) return p;
        auto it = imports.find(sym);
        if (it == imports.end()) return nullptr;
        std::lock_guard<std::mutex> lk(m);
        void*& s = stubbed[sym];
        if (!s && stubs < kStubs) {
            g_stub_lib[stubs] = it->second.first.c_str();
            g_stub_name[stubs] = it->second.second.c_str();
            s = (void*)g_stubs[stubs++];
        }
        return s;
    }
};

class SelfGenerator : public llvm::orc::DefinitionGenerator {
public:
    explicit SelfGenerator(Resolver& r) : r_(r) {}
    llvm::Error tryToGenerate(llvm::orc::LookupState&, llvm::orc::LookupKind, llvm::orc::JITDylib& jd,
                              llvm::orc::JITDylibLookupFlags, const llvm::orc::SymbolLookupSet& syms) override {
        llvm::orc::SymbolMap found;
        for (auto& [name, flags] : syms)
            if (void* p = r_.resolve((*name).str()))
                found[name] = {llvm::orc::ExecutorAddr::fromPtr(p), llvm::JITSymbolFlags::Exported | llvm::JITSymbolFlags::Callable};
        if (found.empty()) return llvm::Error::success();
        return jd.define(llvm::orc::absoluteSymbols(std::move(found)));
    }

private:
    Resolver& r_;
};

std::string read_file(const std::string& path) {
    std::ifstream f(path, std::ios::binary);
    return std::string(std::istreambuf_iterator<char>(f), {});
}

bool write_file(const std::string& path, const std::string& s) {
    std::ofstream f(path, std::ios::binary | std::ios::trunc);
    f << s;
    return f.good();
}

std::string hex(const uint8_t* p, size_t n) {
    std::string s;
    char b[3];
    for (size_t i = 0; i < n; i++) snprintf(b, sizeof b, "%02x", p[i]), s += b;
    return s;
}


