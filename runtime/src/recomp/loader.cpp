std::string code_base_key(const std::string& rpxPath) {
    std::string rpx = read_file(rpxPath);
    if (rpx.empty()) return "";
    uint8_t h[20], hk[20];
    disc::sha1((const uint8_t*)rpx.data(), rpx.size(), h);
    disc::sha1((const uint8_t*)wwhd_hooks, (size_t)(wwhd_hooks_end - wwhd_hooks), hk);
    std::string key = std::string("recompiler ") + WWHD_RECOMP_VERSION + "\nhooks " + hex(hk, 20) + "\nrpx " + hex(h, 20) + "\ncpu " +
                      host_features() + "\nopt " + std::to_string(kDefaultOptLevel) + "\n" + code_switches() + "\n";
    // another release: its address map decides the function names
    uint32_t entry = rpx.size() >= 0x1C ? (uint8_t)rpx[0x18] << 24 | (uint8_t)rpx[0x19] << 16 | (uint8_t)rpx[0x1A] << 8 | (uint8_t)rpx[0x1B] : 0;
    if (release::known_entry(entry) && entry != kSupportedEntryPoint) {
        std::string map = release::map_text(entry);
        uint8_t hm[20];
        disc::sha1((const uint8_t*)map.data(), map.size(), hm);
        key += "map " + hex(hm, 20) + "\n";
    }
    return key;
}

std::string code_cache_key(const std::string& rpxPath) {
    std::string key = code_base_key(rpxPath);
    if (key.empty()) return key;
    if (const CodePatch* p = code_patch(); p && !p->key.empty()) key += p->key + "\n";  // mod packs (packs.h)
    return key;
}

namespace {
constexpr int kKeepSets = 3;  // manifests (code sets) whose objects stay in the cache

std::string manifest_path(const std::string& dir, const std::string& key) {
    uint8_t h[20];
    disc::sha1((const uint8_t*)key.data(), key.size(), h);
    return dir + "/set_" + hex(h, 20);
}

// the object files of `key` ("" key or a missing / foreign manifest: none)
bool manifest_objects(const std::string& dir, const std::string& key, std::vector<std::string>& out) {
    if (key.empty()) return false;
    std::string m = read_file(manifest_path(dir, key));
    size_t sep = m.find("\n---\n");
    if (sep == std::string::npos || m.substr(sep + 5) != key) return false;
    out.clear();
    for (size_t i = 0; i < sep;) {
        size_t e = m.find('\n', i);
        if (e == std::string::npos || e > sep) e = sep;
        if (e > i) out.push_back(m.substr(i, e - i));
        i = e + 1;
    }
    return !out.empty();
}
}  // namespace

bool code_cache_ready(const std::string& dir, const std::string& key) {
    std::vector<std::string> objs;
    if (!manifest_objects(dir, key, objs)) return false;
    struct stat st;
    for (auto& o : objs)
        if (stat((dir + "/" + o).c_str(), &st) != 0) return false;
    return true;
}

void begin_code_cache(const std::string& dir) {
    mkdir(dir.c_str(), 0700);
    if (DIR* d = opendir(dir.c_str())) {  // the old layout: code_NNN.o, complete, building
        while (dirent* e = readdir(d)) {
            std::string n = e->d_name;
            if (n.rfind("code_", 0) == 0 || n == "complete" || n == "building") unlink((dir + "/" + n).c_str());
        }
        closedir(d);
    }
}

bool finish_code_cache(const std::string& dir, const std::string& key, const std::vector<std::string>& objects, std::string& err) {
    std::string m;
    for (auto& o : objects) m += o + "\n";
    m += "---\n" + key;
    std::string path = manifest_path(dir, key);
    if (!write_file(path + ".tmp", m) || rename((path + ".tmp").c_str(), path.c_str()) != 0) {
        err = "cannot write " + path;
        return false;
    }
    // keep the objects of the newest manifests (this one included), remove the rest
    std::vector<std::pair<long, std::string>> sets;
    std::vector<std::string> files;
    if (DIR* d = opendir(dir.c_str())) {
        while (dirent* e = readdir(d)) {
            std::string n = e->d_name;
            struct stat st;
            if (n.rfind("set_", 0) == 0 && n.find('.') == std::string::npos && stat((dir + "/" + n).c_str(), &st) == 0)
                sets.push_back({(long)st.st_mtime, n});
            else if (n.rfind("m_", 0) == 0)
                files.push_back(n);
        }
        closedir(d);
    }
    std::sort(sets.rbegin(), sets.rend());
    std::set<std::string> keep(objects.begin(), objects.end());
    for (size_t i = 0; i < sets.size(); i++) {
        std::string s = read_file(dir + "/" + sets[i].second);
        if ((int)i >= kKeepSets && dir + "/" + sets[i].second != path) {
            unlink((dir + "/" + sets[i].second).c_str());
            continue;
        }
        size_t sep = s.find("\n---\n");
        for (size_t p = 0; sep != std::string::npos && p < sep;) {
            size_t e = s.find('\n', p);
            if (e == std::string::npos || e > sep) e = sep;
            keep.insert(s.substr(p, e - p));
            p = e + 1;
        }
    }
    for (auto& f : files)
        if (!keep.count(f)) unlink((dir + "/" + f).c_str());
    return true;
}

bool load_game_code(const std::string& rpxPath, const std::string& dir, std::string& err) {
    auto t0 = std::chrono::steady_clock::now();
    auto ms = [&] { return (long)std::chrono::duration_cast<std::chrono::milliseconds>(std::chrono::steady_clock::now() - t0).count(); };
    static Program prog;  // the tables point into it
    if (!prog.load(rpxPath, err)) return false;
    if (!release::select(prog.entry)) {
        err = rpxPath + " is not a supported game version";
        return false;
    }
    log_msg("[recomp] game release: %s", release::name());
    crash_info::set("code", std::string("compiled on the device: recompiler ") + WWHD_RECOMP_VERSION + ", -O" +
                                std::to_string(kDefaultOptLevel) + ", CPU features " + host_features());
    long tAnalyze = ms();

    static Resolver res;
    Dl_info info;
    if (!dladdr((void*)&load_game_code, &info) || !(res.self = dlopen(info.dli_fname, RTLD_NOW | RTLD_NOLOAD))) {
        err = "cannot find the runtime library";
        return false;
    }
    for (auto& [slot, im] : prog.imports)
        if (im.function) res.imports[import_symbol(im)] = {im.lib, im.name};

    LLVMInitializeAArch64TargetInfo();
    LLVMInitializeAArch64Target();
    LLVMInitializeAArch64TargetMC();
    auto jit = llvm::orc::LLJITBuilder()
                   .setJITTargetMachineBuilder(llvm::orc::JITTargetMachineBuilder(llvm::Triple("aarch64-unknown-linux-android30")))
                   .setPlatformSetUp(llvm::orc::setUpInactivePlatform)
                   .setObjectLinkingLayerCreator([](llvm::orc::ExecutionSession& es, const llvm::Triple&)
                                                     -> llvm::Expected<std::unique_ptr<llvm::orc::ObjectLayer>> {
                       auto ol = std::make_unique<llvm::orc::ObjectLinkingLayer>(es);
                       // the code's unwind tables (compile.cpp), for backtraces in crash logs
                       ol->addPlugin(std::make_unique<llvm::orc::EHFrameRegistrationPlugin>(
                           es, std::make_unique<llvm::jitlink::InProcessEHFrameRegistrar>()));
                       return ol;
                   })
                   .create();
    if (!jit) {
        err = "JIT: " + llvm::toString(jit.takeError());
        return false;
    }
    static std::unique_ptr<llvm::orc::LLJIT> keep;  // the code lives as long as the process
    keep = std::move(*jit);
    llvm::orc::JITDylib& jd = keep->getMainJITDylib();
    jd.addGenerator(std::make_unique<SelfGenerator>(res));

    std::vector<std::string> objectFiles;
    const std::string key = code_cache_key(rpxPath);
    if (!manifest_objects(dir, key, objectFiles)) {
        err = "no compiled code for this game and mod packs in " + dir;
        return false;
    }
    utimes(manifest_path(dir, key).c_str(), nullptr);  // the newest set: its objects stay (finish_code_cache)
    size_t objects = 0;
    for (auto& name : objectFiles) {
        auto buf = llvm::MemoryBuffer::getFile(dir + "/" + name);
        if (!buf) {
            err = "missing " + name;
            return false;
        }
        if (auto e = keep->addObjectFile(std::move(*buf))) {
            err = name + ": " + llvm::toString(std::move(e));
            return false;
        }
        objects++;
    }
    if (!objects) {
        err = "no compiled code in " + dir;
        return false;
    }

    // one lookup links everything; the game functions, then the runtime's direct references
    llvm::orc::ExecutionSession& es = keep->getExecutionSession();
    llvm::orc::SymbolLookupSet want;
    std::vector<llvm::orc::SymbolStringPtr> names;
    char buf[32];
    for (uint32_t a : prog.entries) {  // named by their USA address (emit.cpp, sym)
        uint32_t u = release::usa_code(a);
        snprintf(buf, sizeof buf, u ? "f_%08X" : "f_E%08X", u ? u : a);
        names.push_back(es.intern(buf));
    }
    for (unsigned i = 0; i < wwhd_jit_count; i++) names.push_back(es.intern(wwhd_jit_names[i]));
    for (auto& n : names) want.add(n);
    auto syms = es.lookup(llvm::orc::makeJITDylibSearchOrder(&jd), std::move(want));
    if (!syms) {
        err = "linking: " + llvm::toString(syms.takeError());
        return false;
    }
    auto addr = [&](size_t i) { return (*syms)[names[i]].getAddress().toPtr<PpcFunc>(); };

    static std::vector<RecompEntry> funcs;
    funcs.clear();
    for (size_t i = 0; i < prog.entries.size(); i++) funcs.push_back({prog.entries[i], addr(i)});
    for (unsigned i = 0; i < wwhd_jit_count; i++) wwhd_jit_slots[i] = addr(prog.entries.size() + i);

    static std::vector<RecompImport> imports;
    imports.clear();
    for (auto& [slot, im] : prog.imports) {
        PpcFunc fn = im.function ? (PpcFunc)res.resolve(import_symbol(im)) : nullptr;
        if (im.function && !fn) {
            err = "too many unimplemented imports";
            return false;
        }
        imports.push_back({slot, im.function ? slot : im.dataAddr, im.lib.c_str(), im.name.c_str(), im.function, fn});
    }
    // debug: WWHD_PERF_MAP=1 writes <code dir>/perf.map (host address, guest address, sorted) to
    // attribute profiler samples in the game code to its functions
    if (getenv("WWHD_PERF_MAP")) {
        std::vector<std::pair<uintptr_t, uint32_t>> m;
        for (auto& f : funcs) m.push_back({(uintptr_t)f.fn, f.addr});
        std::sort(m.begin(), m.end());
        if (FILE* out = fopen((dir + "/perf.map").c_str(), "w")) {
            for (auto& [h, g] : m) fprintf(out, "%lx %08X\n", (unsigned long)h, release::usa_code(g) ? release::usa_code(g) : g);
            fclose(out);
        }
    }
    g_recomp_funcs = funcs.data();
    g_recomp_func_count = (unsigned)funcs.size();
    g_recomp_imports = imports.data();
    g_recomp_import_count = (unsigned)imports.size();
    g_recomp_entry_point = prog.entry;
    log_msg("[recomp] loaded %zu objects: %zu functions, %zu imports (%zu unimplemented); analysis %ld ms, total %ld ms", objects,
            funcs.size(), imports.size(), res.stubs, tAnalyze, ms());
    return true;
}

